#!/usr/bin/env node
'use strict';

/**
 * Generates public/js/shared/llpa-matrix.js from the legacy LLPM tool's ES-module matrix file,
 * so the classic-script calculators and the module-based LLPM tool share one set of numbers.
 *
 * Usage: node scripts/sync-llpa-matrix.js
 * test/llpa-engine.test.js fails if the two files drift apart.
 */

const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', 'legacy', 'llpm-calc', 'llpa-matrix-2026-01-28.js');
const OUT = path.join(__dirname, '..', 'public', 'js', 'shared', 'llpa-matrix.js');

const src = fs.readFileSync(SRC, 'utf8');
const marker = 'export const LLPA_MATRIX = ';
const at = src.indexOf(marker);
if (at < 0) throw new Error('export const LLPA_MATRIX not found in ' + SRC);
const literal = src.slice(at + marker.length).replace(/;\s*$/, '');

const out = `/**
 * Fannie Mae LLPA Matrix as data. GENERATED by scripts/sync-llpa-matrix.js from
 * legacy/llpm-calc/${path.basename(SRC)} — edit that file, then re-run the script.
 * Values are in points (0.375 = 0.375 points). Exposed as MSFG.LLPA_MATRIX.
 */
/* global globalThis */
(function() {
  'use strict';
  const root = typeof window !== 'undefined' ? window : globalThis;
  root.MSFG = root.MSFG || {};
  root.MSFG.LLPA_MATRIX = ${literal.trim()};
})();
`;
fs.writeFileSync(OUT, out);
console.log('wrote', path.relative(process.cwd(), OUT), `(${out.length} bytes)`);
